#!/usr/bin/env bash
#
# Deterministically generates the 8 ChatGPT Custom GPT Knowledge bundles
# under chatgpt/knowledge/ from an explicit allowlist of canonical
# repository sources. See chatgpt/knowledge-manifest.md for the full
# bundle-to-source mapping and rationale.
#
# Never edit a file under chatgpt/knowledge/ directly — rebuild it here.
#
# Works when invoked from inside or outside the repository root, since all
# paths are resolved relative to this script's own location.

set -euo pipefail

SCRIPT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" >/dev/null 2>&1 && pwd -P)"
REPO_ROOT="$(cd -- "${SCRIPT_DIR}/.." >/dev/null 2>&1 && pwd -P)"

KNOWLEDGE_DIR="${REPO_ROOT}/chatgpt/knowledge"

fail() {
  echo "error: $1" >&2
  exit 1
}

GENERATED_NOTICE='<!--
Generated from canonical Career Targeting Intelligence repository sources.
Do not edit this file manually.
Rebuild it using the ChatGPT Knowledge build script
(scripts/build-chatgpt-knowledge.sh or .ps1).
-->'

# Explicit bundle -> source allowlist. One "bundle:source1,source2,..." entry
# per generated file, in generation order. Source paths are repo-root-relative.
BUNDLES=(
  "01-product-and-terminology.md:core/product-definition.md,core/scope-and-non-goals.md,core/data-model.md"
  "02-candidate-and-search.md:schemas/candidate-profile.schema.md,schemas/search-criteria.schema.md,workflows/analyze-candidate.md,workflows/build-search-criteria.md"
  "03-company-intelligence.md:schemas/company-record.schema.md,workflows/discover-companies.md,workflows/classify-and-rank-companies.md,ranking/company-ranking-model.md"
  "04-people-and-activity.md:schemas/person-record.schema.md,schemas/activity-record.schema.md,workflows/discover-people.md,workflows/verify-activity.md"
  "05-ranking-and-exclusions.md:ranking/person-ranking-model.md,ranking/exclusion-policy.md,ranking/outreach-priority-model.md"
  "06-workflow-and-state.md:core/workflow.md,schemas/research-state.schema.md,workflows/full-journey.md,workflows/focused-task-routing.md,workflows/resume-journey.md,workflows/build-outreach-queue.md"
  "07-evidence-confidence-freshness.md:core/source-policy.md,core/confidence-model.md,core/freshness-policy.md,core/quality-gates.md"
  "08-output-contracts.md:core/output-contracts.md,outputs/candidate-profile-template.md,outputs/search-criteria-template.md,outputs/company-map-template.md,outputs/excluded-companies-template.md,outputs/people-map-template.md,outputs/activity-verification-template.md,outputs/outreach-queue-template.md,outputs/csv-column-contracts.md"
)

# Validate every canonical source exists before generating anything.
for entry in "${BUNDLES[@]}"; do
  sources="${entry#*:}"
  IFS=',' read -ra SRC_LIST <<< "${sources}"
  for src in "${SRC_LIST[@]}"; do
    [ -f "${REPO_ROOT}/${src}" ] || fail "required canonical source not found: ${REPO_ROOT}/${src}"
  done
done

mkdir -p -- "${KNOWLEDGE_DIR}"

# Remove stale generated files not on the current allowlist.
ALLOWED_NAMES=()
for entry in "${BUNDLES[@]}"; do
  ALLOWED_NAMES+=("${entry%%:*}")
done
if [ -d "${KNOWLEDGE_DIR}" ]; then
  while IFS= read -r -d '' existing; do
    name="$(basename -- "${existing}")"
    keep=0
    for allowed in "${ALLOWED_NAMES[@]}"; do
      [ "${name}" = "${allowed}" ] && keep=1 && break
    done
    if [ "${keep}" -eq 0 ]; then
      rm -f -- "${existing}"
    fi
  done < <(find "${KNOWLEDGE_DIR}" -maxdepth 1 -type f -name '*.md' -print0)
fi

# Generate each bundle deterministically.
for entry in "${BUNDLES[@]}"; do
  bundle_name="${entry%%:*}"
  sources="${entry#*:}"
  IFS=',' read -ra SRC_LIST <<< "${sources}"
  out_path="${KNOWLEDGE_DIR}/${bundle_name}"
  tmp_path="${out_path}.tmp"
  src_count="${#SRC_LIST[@]}"

  {
    printf '%s\n\n' "${GENERATED_NOTICE}"
    printf '# %s\n\n' "${bundle_name%.md}"
    idx=0
    for src in "${SRC_LIST[@]}"; do
      idx=$((idx + 1))
      printf '## Source: `%s`\n\n' "${src}"
      # Preserve source content without silent rewriting; normalize CRLF to LF.
      sed 's/\r$//' "${REPO_ROOT}/${src}"
      if [ "${idx}" -lt "${src_count}" ]; then
        printf '\n\n---\n\n'
      else
        printf '\n'
      fi
    done
  } > "${tmp_path}"

  mv -- "${tmp_path}" "${out_path}"
done

echo "Generated ChatGPT Knowledge bundles in: ${KNOWLEDGE_DIR}"
echo ""
echo "Generated files:"
for name in "${ALLOWED_NAMES[@]}"; do
  echo "chatgpt/knowledge/${name}"
done
